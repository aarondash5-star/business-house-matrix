#!/usr/bin/env python3
"""Autonomous Dev Matrix stage-1 control plane: durable, explainable orchestration.

Cognitive planning can be arbitrarily detailed and recursive. Capability execution
is still trusted-code controlled. This version runs an exact offline simulation
with independent QA receipts, never a real shell/site/repo change. It is not v6.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import sqlite3
import sys
import time

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gate_s_v2 import validate, PlanError

# Registry is trusted configuration, NEVER generated by a model.
REGISTRY = {
 "research":{"worker":"public_research","capability":"read_only_research"},
 "design":{"worker":"private_design","capability":"offline_design"},
 "development":{"worker":"dev_sandbox","capability":"isolated_dev_candidate"},
 "qa":{"worker":"independent_qa","capability":"nonproduction_quality"},
 "security":{"worker":"security_review","capability":"read_only_security"},
 "review":{"worker":"human_owner","capability":"approval_queue"},
}
CAPABILITY_MODE="simulation_only"
POLICY={
 "execute_real_tools":False, "model_controls_permissions":False,
 "allow_publish":False, "allow_merge":False, "allow_spend":False,
 "allow_privilege_change":False, "require_owner_review":True,
 "max_parallel_proposals":3, "auto_retry":False,
}

class AutonomyError(ValueError): pass

def sha(data):
 return hashlib.sha256(json.dumps(data,sort_keys=True,separators=(",",":")).encode()).hexdigest()

def policy_check(plan):
 try: validate(plan)
 except PlanError as exc:raise AutonomyError("plan_invalid:"+str(exc)) from exc
 tasks=plan["tasks"]
 if len(tasks)>30:raise AutonomyError("too_many_work_packages")
 if tasks[-1]["role"]!="review":raise AutonomyError("owner_last")
 if any(t["role"]=="review" for t in tasks[:-1]):raise AutonomyError("premature_approval")
 qa={t["id"] for t in tasks if t["role"]=="qa"}
 security={t["id"] for t in tasks if t["role"]=="security"}
 if not qa or not security:raise AutonomyError("qa_security_missing")
 # Explicitly require the final owner decision to follow both QA and security
 # via transitive dependency paths; other tasks can run concurrently.
 deps={t["id"]:set(t["depends_on"]) for t in tasks}
 def predecessors(task_id):
  found=set()
  stack=list(deps[task_id])
  while stack:
   x=stack.pop()
   if x not in found:
    found.add(x);stack+=list(deps[x])
  return found
 before_review=predecessors(tasks[-1]["id"])
 if not (qa & before_review) or not (security & before_review):
  raise AutonomyError("qa_and_security_must_precede_approval")
 # Enforce that all development deliverables have at least one subsequent QA gate
 # in their dependency path leading to signoff; otherwise they can bypass QA.
 for item in tasks:
  if item["role"]=="development" and not any(item["id"] in predecessors(x) for x in qa):
   raise AutonomyError("unverified_development:"+item["id"])
 # Security audit at least comes after a development or research task.
 if not any(predecessors(s) for s in security):raise AutonomyError("unscoped_security")
 return plan

def layers(plan):
 """Derive safe independent ready batches from DAG. Never assume fixed chain."""
 policy_check(plan)
 tasks=plan["tasks"]
 completed=set(); batches=[]
 while len(completed)<len(tasks):
  ready=[t["id"] for t in tasks if t["id"] not in completed
         and set(t["depends_on"]).issubset(completed)]
  if not ready:raise AutonomyError("cyclic_or_unsatisfied_dag")
  # No QA, security or review item is run concurrently with a state it audits.
  if any(next(t["role"] for t in tasks if t["id"]==x) in ("qa","security","review") for x in ready):
   critical=[x for x in ready if next(t["role"] for t in tasks if t["id"]==x) in ("qa","security","review")]
   ready=[critical[0]]
  else:ready=ready[:POLICY["max_parallel_proposals"]]
  batches.append(ready);completed.update(ready)
 return batches

def stage_plan(plan,db_path):
 """Persist a planning proposal and signed input digest; does not dispatch work."""
 policy_check(plan)
 if not isinstance(db_path,Path) or db_path.exists() or db_path.is_symlink():
  raise AutonomyError("new_separate_run_database_required")
 db_path.parent.mkdir(parents=True,exist_ok=True)
 with sqlite3.connect(str(db_path)) as db:
  db.execute("CREATE TABLE events (seq INTEGER PRIMARY KEY AUTOINCREMENT, event TEXT NOT NULL, task_id TEXT, body_json TEXT NOT NULL)")
  db.execute("CREATE TABLE tasks (task_id TEXT PRIMARY KEY, role TEXT NOT NULL, state TEXT NOT NULL, proposal_digest TEXT NOT NULL)")
  db.execute("INSERT INTO events(event,task_id,body_json) VALUES (?,?,?)",
      ("proposal_created",None,json.dumps({"sha256":sha(plan),"mode":CAPABILITY_MODE})))
  for t in plan["tasks"]:
   db.execute("INSERT INTO tasks VALUES (?,?,?,?)",(t["id"],t["role"],"proposed",sha(t)))
 return {"mode":CAPABILITY_MODE,"plan_sha256":sha(plan),"total_tasks":len(plan["tasks"]),
         "batches":layers(plan),"policy":POLICY}

def simulated_dispatch(plan,db_path, fail_ids=None):
 """Exercises routing/dependencies, NOT actual specialist worker or model calls."""
 if fail_ids is None:fail_ids=set()
 if not isinstance(fail_ids,set) or not all(isinstance(x,str) for x in fail_ids):
  raise AutonomyError("failure_fixture_format")
 tasks={t["id"]:t for t in plan["tasks"]}
 all_ids=set(tasks)
 if not fail_ids.issubset(all_ids):raise AutonomyError("unknown_failure_fixture")
 if not db_path.is_file():raise AutonomyError("run_database_missing")
 results={}
 with sqlite3.connect(str(db_path)) as db:
  for group in layers(plan):
   for tid in group:
    task=tasks[tid]
    dependencies=task["depends_on"]
    if any(results.get(d)!="passed_simulated" for d in dependencies):
     state="blocked_dependency"
    elif tid in fail_ids:
     state="failed_simulated"
    elif task["role"]=="review":
     # An owner decision is ALWAYS external, even after simulated QA passes.
     state="awaiting_human_approval"
    else:state="passed_simulated"
    results[tid]=state
    db.execute("UPDATE tasks SET state=? WHERE task_id=?",(state,tid))
    db.execute("INSERT INTO events(event,task_id,body_json) VALUES (?,?,?)",
     ("simulated_receipt",tid,json.dumps({"state":state,"worker":REGISTRY[task["role"]]["worker"],
       "worker_actually_invoked":False,"external_actions_executed":False,
       "dependencies":dependencies,"timestamp_unix":time.time()})))
    # No auto retry. Even a passing QA receipt from simulation grants no execution.
 overall=("blocked" if any(v in ("failed_simulated","blocked_dependency") for v in results.values())
  else "owner_review_required")
 return {"mode":CAPABILITY_MODE,"state":overall,"results":results,
         "executed_real_work":False,"production_changed":False,"owner_approval":False}

def main():
 ap=argparse.ArgumentParser()
 ap.add_argument("--plan",required=True,help="Reviewed JSON work order (no model tool calls)")
 ap.add_argument("--database",required=True,help="New sqlite file in isolated staging")
 ap.add_argument("--simulate",action="store_true")
 ap.add_argument("--fail-task",action="append",default=[])
 args=ap.parse_args()
 if not args.simulate:raise AutonomyError("real_dispatch_not_enrolled")
 plan=json.loads(Path(args.plan).read_text())
 db=Path(args.database).resolve()
 if not db.parent.is_dir():raise AutonomyError("staging_directory_missing")
 proposal=stage_plan(plan,db)
 report={"proposal":proposal,
         "simulation":simulated_dispatch(plan,db,set(args.fail_task))}
 print(json.dumps(report,indent=2))
if __name__=="__main__":
 try:main()
 except (ValueError,OSError,sqlite3.Error) as exc:
  print(json.dumps({"status":"blocked","reason":str(exc),"external_actions_executed":False}))
  sys.exit(2)
